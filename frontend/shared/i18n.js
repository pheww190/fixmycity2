function getCurrentLanguage() {
  return localStorage.getItem('mg_lang') || 'en';
}

function applyTranslations() {
  const lang = getCurrentLanguage();
  const t = translations[lang] || translations.en;

  // 1. Text elements by data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      el.textContent = t[key];
    }
  });

  // 2. Placeholder attributes by data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) {
      el.placeholder = t[key];
    }
  });

  // 3. Sync all language dropdowns on the page
  document.querySelectorAll('.lang-select, .lang-selector select, select[name="lang"]').forEach(sel => {
    sel.value = lang;
  });

  // Update HTML lang attribute
  document.documentElement.lang = lang;
}

function changeLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  localStorage.setItem('mg_lang', lang);
  applyTranslations();
}
window.changeLanguage = changeLanguage;

document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
  // Listen to any select changes
  document.querySelectorAll('.lang-select, .lang-selector select').forEach(sel => {
    sel.value = getCurrentLanguage();
    sel.addEventListener('change', (e) => {
      changeLanguage(e.target.value);
    });
  });
});
